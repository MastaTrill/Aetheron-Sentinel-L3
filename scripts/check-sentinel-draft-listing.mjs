#!/usr/bin/env node
import { readFileSync } from 'node:fs';
import assert from 'node:assert/strict';
const manifest=JSON.parse(readFileSync('release-evidence/sentinel-mainnet/redeployment/deployment-manifest.json','utf8'));
const listing=JSON.parse(readFileSync('config/sentinel-replacement-listing.draft.json','utf8'));
const sender='0xa4737aa4b1e8a3c8f221be9e55f5bda307ecc1fa';
const WAD=10n**18n;
assert.equal(manifest.status,'preparation-only');
assert.equal(manifest.token.yearlyMintRate,'0');
assert.equal(manifest.token.decimals,18);
assert.equal(BigInt(manifest.token.initialSupply),1000000000n*WAD);
assert.equal(manifest.token.numTokensToSell,manifest.token.initialSupply);
assert.equal(manifest.execution.authorizedBaseMainnetSender.toLowerCase(),sender);
assert.equal(manifest.execution.governanceModel,'no-op');
assert.equal(manifest.execution.migrationModel,'no-op');
assert.equal(manifest.execution.valueWei,'0');
assert.equal(manifest.networks.baseMainnet.chainId,8453);
assert.equal(manifest.safety.signingEnabled,false);
assert.equal(manifest.safety.broadcastEnabled,false);
assert.equal(manifest.safety.baseMainnetAuthorized,false);
assert.equal(manifest.rehearsal.protectedBroadcastAuthorized,false);
const expected={'doppler-protocol':50000000000000000n,'bankr-ecosystem':19000000000000000n,'aetheron-treasury':570000000000000000n,'bankr-platform-integrator':361000000000000000n};
const shares=manifest.pool.beneficiaries;
assert.equal(shares.length,4);
assert.equal(shares.reduce((n,b)=>n+BigInt(b.shares),0n),WAD);
for(const b of shares){assert.equal(BigInt(b.shares),expected[b.role]);if(b.role==='aetheron-treasury')assert.equal(b.beneficiary.toLowerCase(),sender);}
assert.equal(listing.chainId,8453);
assert.equal(listing.tokenName,manifest.token.name);
assert.equal(listing.tokenSymbol,manifest.token.symbol);
assert.equal(listing.decimals,manifest.token.decimals);
assert.equal(listing.initialSupplyBaseUnits,manifest.token.initialSupply);
assert.equal(listing.tokenURI,manifest.token.tokenURI);
assert.equal(listing.yearlyMintRateWad,manifest.token.yearlyMintRate);
assert.equal(listing.contractAddress,null,'predicted/legacy addresses must not be published');
assert.equal(listing.explorerTokenUrl,null);
assert.equal(listing.logo.approvedByOwner,false,'icon asset has not been independently verified/hosted');
assert.equal(listing.profileSubmission.status,'not-submitted');
assert.equal(listing.safety.mainnetAuthorized,false);
console.log('PASS: draft manifest/listing consistency, beneficiary shares, supply arithmetic and Mainnet HOLD guardrails.');
console.log('NOT PROVEN: immutable mint restrictions, pinned factory source, metadata content, icon hosting, BaseScan approval, simulation or deployment.');
