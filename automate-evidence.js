import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import { ethers } from 'ethers';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const EVIDENCE_PATH = path.join(__dirname, '..', 'MAINNET_EVIDENCE_PACKET.md');
const CONTRACTS_JS_PATH = path.join(__dirname, '..', 'site', 'contracts.js');
const DATA_PATH = path.join(__dirname, '..', 'mainnet-deployment-data.json');

async function main() {
  if (!fs.existsSync(DATA_PATH)) {
    console.error('❌ Error: mainnet-deployment-data.json not found. Run deployment first.');
    process.exit(1);
  }

  const data = JSON.parse(fs.readFileSync(DATA_PATH, 'utf8'));
  let evidenceContent = fs.readFileSync(EVIDENCE_PATH, 'utf8');

  console.log('🚀 Starting Evidence Automation...');

  // 1. Populate Evidence Packet Tables
  // This regex looks for the contract name in the first column and replaces the [TBD] placeholders
  if (data.contracts) {
    for (const [name, details] of Object.entries(data.contracts)) {
      const tableRegex = new RegExp(`\\| ${name} \\| \\[TBD\\] \\| \\[TBD\\] \\|`, 'g');
      const replacement = `| ${name} | \`${details.hash}\` | ${details.block} |`;
      evidenceContent = evidenceContent.replace(tableRegex, replacement);
    }
  }

  // 2. Populate Action Hashes (Section 2, 3, 4)
  // This matches descriptions like "Grant TIMELOCK_ADMIN to Multisig | [TBD] |"
  if (data.actions) {
    for (const [actionDesc, hash] of Object.entries(data.actions)) {
      evidenceContent = evidenceContent.replace(
        `${actionDesc} | [TBD] |`,
        `${actionDesc} | \`${hash}\` |`
      );
    }
  }

  fs.writeFileSync(EVIDENCE_PATH, evidenceContent);
  console.log('✅ MAINNET_EVIDENCE_PACKET.md populated with live hashes.');

  // 3. Update site/contracts.js with Hashes
  const contractsObj = {};
  for (const [name, details] of Object.entries(data.contracts || {})) {
    contractsObj[name] = {
      address: details.address,
      explorerUrl: `https://etherscan.io/address/${details.address}`,
      deployHash: details.hash, // Added deployHash field
      verified: true,
    };
  }

  // 4. Final Ownership Verification
  console.log('\n--- Final Ownership Verification ---');
  const multiSigAddress = data.contracts.SentinelMultiSigVault?.address;
  const coreAddress = data.contracts.SentinelCore?.address;

  if (multiSigAddress && coreAddress && process.env.RPC_URL) {
    const rpcProvider = new ethers.JsonRpcProvider(process.env.RPC_URL);
    const coreContract = new ethers.Contract(
      coreAddress,
      ['function owner() view returns (address)'],
      rpcProvider
    );
    const currentOwner = await coreContract.owner();
    if (currentOwner.toLowerCase() === multiSigAddress.toLowerCase()) {
      console.log(
        `✅ Ownership Verified: SentinelMultiSigVault (${multiSigAddress}) owns SentinelCore.`
      );
    } else {
      console.log(
        `⚠️ Warning: SentinelCore owner is ${currentOwner}, expected MultiSig ${multiSigAddress}.`
      );
    }
  } else {
    console.log('⚠️ Skipping ownership verification (no RPC_URL env or missing addresses).');
  }

  const siteConfig = `// Auto-generated by scripts/automate-evidence.js
// Last updated: ${new Date().toISOString()}
window.SENTINEL_CONTRACTS = ${JSON.stringify(contractsObj, null, 2)};
window.SENTINEL_NETWORK = 'mainnet';
`;

  fs.writeFileSync(CONTRACTS_JS_PATH, siteConfig);
  console.log('✅ site/contracts.js updated with Mainnet addresses and hashes.');
}

main().catch(console.error);
